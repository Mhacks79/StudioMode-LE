bool Verify::IsReadable(const void * p, UInt32 size)
{
	const UInt32 a = (UInt32)p;
	if(!a || (a & 3) || a >= 0xFFFF0000 || a + size < a) return false;

	MEMORY_BASIC_INFORMATION mbi;
	if(!VirtualQuery(p, &mbi, sizeof(mbi))) return false;
	if(mbi.State != MEM_COMMIT) return false;
	if(mbi.Protect & (PAGE_NOACCESS | PAGE_GUARD)) return false;
	return a + size <= (UInt32)mbi.BaseAddress + mbi.RegionSize;
}

bool Verify::Run()
{
	bool ok = true;
	for(UInt32 i = 0; i < sizeof(kSites) / sizeof(kSites[0]); i++)
	{
		const Site & s = kSites[i];
		const UInt8 * live = (const UInt8 *)s.address;
		const UInt32 compare = (s.kind == kCallSite) ? 1 : s.length;

		bool match = true;
		for(UInt32 j = 0; j < compare; j++)
			if(live[j] != s.bytes[j]) { match = false; break; }

		if(!match)
		{
			_ERROR("verify: %s at %08X does not match TESV.exe 1.9.32.0.8", s.name, s.address);
			ok = false;
		}
		else if(s.kind == kCallSite && memcmp(live, s.bytes, s.length) != 0)
			_MESSAGE("verify: %s at %08X already redirected to %08X by another plugin, chaining",
				s.name, s.address, s.address + 5 + *(const SInt32 *)(live + 1));
	}

	if(ok) _MESSAGE("verify: all %u sites match", (UInt32)(sizeof(kSites) / sizeof(kSites[0])));
	return ok;
}
